"""Shared helpers for the deck generator: deterministic YAML output and benchmark scaffolding."""

from __future__ import annotations

import random
from pathlib import Path
from typing import Any

import yaml

DECK_VERSION = "1.0"
STANDARD = Path(__file__).resolve().parents[2] / "benchmarks" / "standard"
HEADER = "# GENERATED by scripts/generate_deck.py — do not edit by hand; change the generator and re-run.\n"


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, s: str):
    style = "|" if "\n" in s else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style=style)


_Dumper.add_representer(str, _str)


def dump(data: dict[str, Any]) -> str:
    return HEADER + yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=1000)


def rng_for(name: str) -> random.Random:
    """One independent, stable stream per generator, so editing one never reshuffles another."""
    return random.Random(f"modelcompare-deck-{DECK_VERSION}-{name}")


def benchmark(name: str, dimension: str, description: str, cases: list[dict], **extra: Any) -> dict[str, Any]:
    return {"name": name, "version": DECK_VERSION, "dimension": dimension, "source": "standard",
            "description": description, **extra, "cases": cases}


